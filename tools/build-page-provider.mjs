/**
 * build-page-provider — bundles the WebView provider entry
 * (packages/protocol/src/webview-entry.ts) into one minified IIFE and writes
 * it as a string module the phone app injects (master plan §4.2: one
 * page-provider source for every body). Deterministic; commit the output.
 *
 *   pnpm page-provider:build
 */
import { createRequire } from 'node:module'
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)
const { build } = require('esbuild')

const out = join(root, 'apps', 'mobile', 'src', 'page-provider.generated.ts')
const result = await build({
  entryPoints: [join(root, 'packages', 'protocol', 'src', 'webview-entry.ts')],
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'es2020',
  platform: 'browser',
  write: false,
  legalComments: 'none',
})
const code = result.outputFiles[0].text
if (/\beval\s*\(|new Function\s*\(/.test(code)) throw new Error('the provider script must not contain eval or new Function')
const budget = 25 * 1024
if (code.length > budget) throw new Error(`page-provider is ${code.length} bytes; the budget is ${budget} (§4.2)`)
const file = `// @generated by tools/build-page-provider.mjs — do not edit; run \`pnpm page-provider:build\`.\n/** The in-app browser's injected provider (master plan §5.3), ${code.length} bytes minified. */\nexport const PAGE_PROVIDER_SCRIPT = ${JSON.stringify(code)}\n`
await mkdir(dirname(out), { recursive: true })
await writeFile(out, file)
console.log(`page-provider: ${code.length} bytes → ${out}`)
