/**
 * build-page-provider — bundles a page-provider entry from
 * `packages/protocol/src` into one minified, self-contained IIFE (master plan
 * §4.2: one page-provider source for every body).
 *
 * Two bodies need one:
 *
 *   'webview'   → `apps/mobile/src/page-provider.generated.ts`, a string module
 *                 the phone injects before content loads (§5.3). Deterministic;
 *                 commit the output.
 *   'extension' → `page-provider.js`, written into the extension build by a
 *                 hook in `apps/extension/wxt.config.ts` and loaded by the
 *                 isolated bridge when a browser rejects a manifest-declared
 *                 `world: 'MAIN'` content script (the AMO fallback, §4.7).
 *
 *   pnpm page-provider:build
 */
import { createRequire } from 'node:module'
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)

/** §4.2: the provider is 25 KB minified or it is not shipping. */
const BUDGET = 25 * 1024

const ENTRIES = {
  webview: join(root, 'packages', 'protocol', 'src', 'webview-entry.ts'),
  extension: join(root, 'packages', 'protocol', 'src', 'extension-entry.ts'),
}

/**
 * Bundle one entry and return the minified IIFE source.
 *
 * @param {'webview' | 'extension'} body
 * @returns {Promise<string>}
 */
export async function buildPageProvider(body) {
  const { build } = require('esbuild')
  const result = await build({
    entryPoints: [ENTRIES[body]],
    bundle: true,
    minify: true,
    format: 'iife',
    target: 'es2020',
    platform: 'browser',
    write: false,
    legalComments: 'none',
  })
  const code = result.outputFiles[0].text
  // The M1 gate, and the extension CSP, both forbid runtime code generation —
  // and the injected copy runs under the *page's* CSP, where it would be
  // blocked rather than merely frowned upon.
  if (/\beval\s*\(|new Function\s*\(/.test(code)) throw new Error(`the ${body} provider script must not contain eval or new Function`)
  if (code.length > BUDGET) throw new Error(`the ${body} page-provider is ${code.length} bytes; the budget is ${BUDGET} (§4.2)`)
  return code
}

async function main() {
  const webview = await buildPageProvider('webview')
  const out = join(root, 'apps', 'mobile', 'src', 'page-provider.generated.ts')
  const file = `// @generated by tools/build-page-provider.mjs — do not edit; run \`pnpm page-provider:build\`.\n/** The in-app browser's injected provider (master plan §5.3), ${webview.length} bytes minified. */\nexport const PAGE_PROVIDER_SCRIPT = ${JSON.stringify(webview)}\n`
  await mkdir(dirname(out), { recursive: true })
  await writeFile(out, file)
  console.log(`page-provider (webview): ${webview.length} bytes → ${out}`)

  // Not written anywhere: the extension build emits its own copy. Building it
  // here keeps the budget and the eval gate on one command.
  const extension = await buildPageProvider('extension')
  console.log(`page-provider (extension): ${extension.length} bytes → emitted by the extension build`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((err) => {
    console.error(err)
    process.exitCode = 1
  })
}
